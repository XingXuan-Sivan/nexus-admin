package com.nexusadmin.core;

/**
 * 插件生命周期状态枚举。
 * <p>定义插件从发现到卸载的完整生命周期状态。</p>
 */
public enum PluginState {

    // ===== 启动阶段 =====

    /**
     * 已发现（仅元数据，尚未进行依赖解析）。
     */
    DISCOVERED,

    /**
     * 已解析（冲突、依赖解析完成）。
     */
    RESOLVED,

    /**
     * 已加载（类加载完成）。
     */
    LOADED,

    /**
     * 已初始化（插件初始化回调已执行）。
     */
    INITIALIZED,

    // ===== 运行阶段 =====

    /**
     * 启动中（正在执行启动回调）。
     */
    STARTING,

    /**
     * 运行中（插件已成功启动，正常运行）。
     */
    ACTIVE,

    // ===== 停止阶段 =====

    /**
     * 停止中（正在执行停止回调）。
     */
    STOPPING,

    /**
     * 已停止（插件已停止，可重新启动或卸载）。
     */
    STOPPED,

    // ===== 禁用相关 =====

    /**
     * 已禁用（被禁用，可参与解析但不可运行）。
     */
    DISABLED,

    // ===== 升级阶段 =====

    /**
     * 升级中（正在执行热升级，双实例运行）。
     */
    UPGRADING,

    // ===== 卸载阶段 =====

    /**
     * 已卸载（类加载器已释放，从注册表中移除，终态）。
     */
    UNLOADED,

    // ===== 异常阶段 =====

    /**
     * 失败（生命周期流转过程中发生异常）。
     */
    FAILED
}
